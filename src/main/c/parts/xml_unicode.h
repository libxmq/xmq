#ifndef XML_UNICODE_H
#define XML_UNICODE_H

/* The Unicode (4.0.1, like libxml2) general categories and blocks used by the
   XML Schemas regular expressions (xml_regexp.c): \p{Lu}, \P{IsBasicLatin}, \d, \w.
   The functions are named like the libxml2 xmlUCSIsCat* (codegen/unicode.inc) and
   xmlUCSIsBlock functions they are ported from. The tables in xml_unicode.c are
   generated by scripts/generate_xml_unicode_tables.py from libxml2.
   They return 1 if the code point is in the category, 0 if not. */

int xml_ucs_is_cat_c(int code);
int xml_ucs_is_cat_cc(int code);
int xml_ucs_is_cat_cf(int code);
int xml_ucs_is_cat_co(int code);
int xml_ucs_is_cat_l(int code);
int xml_ucs_is_cat_ll(int code);
int xml_ucs_is_cat_lm(int code);
int xml_ucs_is_cat_lo(int code);
int xml_ucs_is_cat_lt(int code);
int xml_ucs_is_cat_lu(int code);
int xml_ucs_is_cat_m(int code);
int xml_ucs_is_cat_mc(int code);
int xml_ucs_is_cat_me(int code);
int xml_ucs_is_cat_mn(int code);
int xml_ucs_is_cat_n(int code);
int xml_ucs_is_cat_nd(int code);
int xml_ucs_is_cat_nl(int code);
int xml_ucs_is_cat_no(int code);
int xml_ucs_is_cat_p(int code);
int xml_ucs_is_cat_pc(int code);
int xml_ucs_is_cat_pd(int code);
int xml_ucs_is_cat_pe(int code);
int xml_ucs_is_cat_pf(int code);
int xml_ucs_is_cat_pi(int code);
int xml_ucs_is_cat_po(int code);
int xml_ucs_is_cat_ps(int code);
int xml_ucs_is_cat_s(int code);
int xml_ucs_is_cat_sc(int code);
int xml_ucs_is_cat_sk(int code);
int xml_ucs_is_cat_sm(int code);
int xml_ucs_is_cat_so(int code);
int xml_ucs_is_cat_z(int code);
int xml_ucs_is_cat_zl(int code);
int xml_ucs_is_cat_zp(int code);
int xml_ucs_is_cat_zs(int code);
/** Is the code point in the block (a name like "BasicLatin"), returns 1 if true,
    0 if false and -1 on unknown block. */
int xml_ucs_is_block(int code, const char *block);

#ifndef XMQ_NO_XSD
#define XML_UNICODE_MODULE
#endif

#endif // XML_UNICODE_H
