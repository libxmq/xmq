    private static final int ENT_F_SEMICOLON = 0x80;
    private static final int ENT_F_SUBTABLE = 0x40;
    private static final int ENT_F_ALL = 0xC0;

    private static int entAlpha(int i)
    {
        return ENT_ALPHA.charAt(i);
    }

    private static int entValue(int i)
    {
        return ENT_VALUES.charAt(i);
    }

    private static int entByte(int i)
    {
        return ENT_STRINGS.charAt(i);
    }

    private static boolean isAsciiLetter(int c)
    {
        return (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z');
    }

    private static boolean isAlnum(int c)
    {
        return isAsciiLetter(c) || (c >= '0' && c <= '9');
    }

    /** Compare like strncmp: the n bytes of s from soff with the entity bytes from boff.
     * Like the NUL terminated input in C, the bytes from end on are 0. */
    private static int compare(byte[] s, int end, int soff, int boff, int n)
    {
        for (int k = 0; k < n; k++)
        {
            int a = soff + k < end ? s[soff + k] & 0xff : 0;
            int b = entByte(boff + k);
            if (a != b) return a - b;
            if (a == 0) return 0;
        }
        return 0;
    }

    /**
     * Find the longest html5 named character reference that is a prefix of the bytes
     * s[off..off+slen) (which start after the &amp;), port of libxml2 htmlFindEntityPrefix.
     * @param s The input bytes.
     * @param off The offset of the reference name.
     * @param slen The number of bytes available.
     * @param is_attr True inside an attribute value.
     * @param nlen Set to the number of bytes of the reference (excluding the &amp;, including a ; if present).
     * @return The utf8 replacement, or null if there is none.
     */
    public static byte[] findEntityPrefix(byte[] s, int off, int slen, boolean is_attr, int[] nlen)
    {
        int match = -1;
        int match_len = 0;
        int soff = 1;

        if (slen < 2) return null;
        int first = s[off] & 0xff;
        if (!isAsciiLetter(first)) return null;

        // Look up range by first character.
        first &= 63;
        int left = entAlpha(first * 3) | entAlpha(first * 3 + 1) << 8;
        int right = left + entAlpha(first * 3 + 2);

        // Binary search.
        while (left < right)
        {
            int mid = left + (right - left) / 2;
            int bytes = entValue(mid);
            int len = entByte(bytes) & ~ENT_F_ALL;

            int cmp = (s[off + soff] & 0xff) - entByte(bytes + 1);

            if (cmp == 0)
            {
                if (slen < len)
                {
                    cmp = compare(s, off + slen, off + soff + 1, bytes + 2, slen - 1);
                    // Prefix can never match.
                    if (cmp == 0) break;
                }
                else
                {
                    cmp = compare(s, off + slen, off + soff + 1, bytes + 2, len - 1);
                }
            }

            if (cmp < 0)
            {
                right = mid;
            }
            else if (cmp > 0)
            {
                left = mid + 1;
            }
            else
            {
                int term = soff + len < slen ? s[off + soff + len] & 0xff : 0;
                boolean is_alnum = isAlnum(term);
                boolean is_term = (term == ';') ||
                    (((entByte(bytes) & ENT_F_SEMICOLON) != 0) && ((!is_attr) || ((!is_alnum) && (term != '='))));

                if (is_term)
                {
                    match = bytes + len + 1;
                    match_len = soff + len;
                    if (term == ';') match_len += 1;
                }

                if ((entByte(bytes) & ENT_F_SUBTABLE) != 0)
                {
                    if (is_term) match += 2;

                    if (is_alnum && (soff + len < slen))
                    {
                        left = mid + entByte(bytes + len + 1);
                        right = left + entByte(bytes + len + 2);
                        soff += len;
                        continue;
                    }
                }

                break;
            }
        }

        if (match < 0) return null;

        nlen[0] = match_len;
        int rlen = entByte(match);
        byte[] r = new byte[rlen];
        for (int k = 0; k < rlen; k++) r[k] = (byte)entByte(match + 1 + k);
        return r;
    }
