    /**
     * Look up an html element (case insensitive), null if unknown.
     * @param name The element name.
     * @return The element or null.
     */
    public static Element element(String name)
    {
        if (name == null) return null;
        return ELEMENTS.get(asciiLower(name));
    }

    /**
     * Does a start tag new_tag implicitly close an open element old_tag? (lowercase names)
     * @param new_tag The new start tag.
     * @param old_tag The open element.
     * @return True if old_tag is closed.
     */
    public static boolean startCloses(String new_tag, String old_tag)
    {
        return START_CLOSE.contains(old_tag + " " + new_tag);
    }

    /**
     * The end tag priority: an end tag only closes elements with lower or equal priority.
     * @param name The element name.
     * @return The priority.
     */
    public static int endPriority(String name)
    {
        Integer p = END_PRIORITIES.get(name);
        return p != null ? p : DEFAULT_PRIORITY;
    }

