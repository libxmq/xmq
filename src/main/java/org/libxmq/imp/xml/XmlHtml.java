    private static String asciiLower(String s)
    {
        StringBuilder b = null;
        for (int i = 0; i < s.length(); i++)
        {
            char c = s.charAt(i);
            if (c >= 'A' && c <= 'Z')
            {
                if (b == null) b = new StringBuilder(s);
                b.setCharAt(i, (char)(c + 32));
            }
        }
        return b == null ? s : b.toString();
    }

